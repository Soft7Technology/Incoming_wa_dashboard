import { Router } from 'express';
import controller from '../app/http/controllers/automationFlow.controller';

const route = Router();
route.use((_req, res, next) => { res.setHeader('Cache-Control', 'no-store'); res.setHeader('Referrer-Policy', 'no-referrer'); next(); });
route.get('/apps', controller.catalog);
route.get('/connections', controller.connections);
route.get('/connections/:connectionId/templates', controller.templates);
route.post('/connections', controller.createConnection);
route.delete('/connections/:connectionId', controller.disconnect);
route.get('/', controller.list);
route.post('/', controller.create);
route.get('/:flowId', controller.get);
route.patch('/:flowId', controller.update);
route.delete('/:flowId', controller.remove);
route.patch('/:flowId/status', controller.status);
route.put('/:flowId/steps', controller.saveSteps);
route.post('/:flowId/steps', controller.addStep);
route.patch('/:flowId/steps/:stepId', controller.updateStep);
route.delete('/:flowId/steps/:stepId', controller.removeStep);
route.post('/:flowId/webhook', controller.webhook);
route.post('/:flowId/webhook/subscribe', controller.subscribeWebhook);
route.get('/:flowId/webhook/status', controller.webhookStatus);
route.delete('/:flowId/webhook/subscription', controller.unsubscribeWebhook);
route.get('/:flowId/events', controller.events);
route.get('/:flowId/events/:eventId', controller.event);
route.post('/:flowId/test-runs', controller.testRun);
route.get('/:flowId/runs', controller.runs);
route.get('/:flowId/runs/:runId', controller.run);
export default route;
