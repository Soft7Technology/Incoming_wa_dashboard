import { Router } from 'express';
import controller from '../app/http/controllers/instagram.controller';
import messenger, { facebookError } from '../app/http/controllers/facebookMessenger.controller';

const route = Router();
route.use(messenger.noStore);
route.get('/setup', controller.setup);
route.post('/oauth/start', controller.start);
route.get('/oauth/pages', controller.candidates);
route.get('/accounts', controller.accounts);
route.post('/accounts/:id/profile/sync', controller.syncProfile);
route.get('/accounts/:id/publishing', controller.publishingSettings);
route.get('/accounts/:id/publications', controller.publications);
route.post('/accounts/:id/publications', controller.preparePost);
route.post('/accounts/:id/publications/:publication/status', controller.publicationStatus);
route.post('/accounts/:id/publications/:publication/publish', controller.publishPost);
route.post('/accounts/:id/publishing/uploads', controller.uploadPublishingMedia);
route.post('/accounts', controller.connect);
route.post('/accounts/:id/disconnect', controller.disconnect);
route.delete('/accounts/:id', controller.erase);
route.get('/accounts/:id/conversations', controller.list('conversation'));
route.post('/accounts/:id/conversations/sync', controller.sync('conversation'));
route.get('/accounts/:id/conversations/:child/messages', controller.messages);
route.post('/accounts/:id/conversations/:child/sync', controller.sync('message'));
route.post('/accounts/:id/conversations/:child/messages', controller.action('message'));
route.get('/accounts/:id/media', controller.list('media'));
route.post('/accounts/:id/media/sync', controller.sync('media'));
route.get('/accounts/:id/media/:child/comments', controller.comments);
route.post('/accounts/:id/media/:child/sync', controller.sync('comment'));
route.post('/accounts/:id/comments/:child/replies', controller.action('reply'));
route.patch('/accounts/:id/comments/:child', controller.action('hide'));
route.use(facebookError);
export default route;
