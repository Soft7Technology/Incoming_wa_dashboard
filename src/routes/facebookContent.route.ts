import { Router } from 'express';
import controller from '../app/http/controllers/facebookContent.controller';
import messenger, { facebookError } from '../app/http/controllers/facebookMessenger.controller';
const route = Router();
route.use(messenger.noStore);
route.get('/setup', controller.setup);
route.post('/oauth/start', controller.start);
route.post('/oauth/token', controller.importToken);
route.get('/oauth/pages', controller.candidates);
route.get('/pages', controller.pages);
route.post('/pages', controller.connect);
route.post('/pages/:id/disconnect', controller.disconnect);
route.delete('/pages/:id', controller.erase);
route.get('/pages/:id/posts', controller.posts);
route.post('/pages/:id/posts/sync', controller.sync);
route.get('/pages/:id/actions', controller.actions);
route.post('/pages/:id/posts', controller.action('create'));
route.patch('/pages/:id/posts/:post', controller.action('edit'));
route.delete('/pages/:id/posts/:post', controller.action('delete'));
route.get('/pages/:id/posts/:post/comments', controller.comments);
route.post('/pages/:id/posts/:post/comments/sync', controller.sync);
route.use(facebookError);
export default route;
