import { Router } from 'express';
import { requireRole } from '@surefy/middleware/jwtAuth.middleware';
import { accountScope } from '../app/http/middleware/accountScope';
import controller, { noStore } from '../app/http/controllers/shopify.controller';
const route = Router();
route.use(accountScope, requireRole('user'), noStore);
route.get('/setup', controller.setup);
route.post('/oauth/start', controller.start);
route.get('/connections', controller.connections);
route.put('/connections/:id/triggers', controller.triggers);
route.post('/connections/:id/sync', controller.sync);
route.delete('/connections/:id', controller.disconnect);
route.get('/connections/:id/events', controller.events);
route.post('/connections/:id/test-flows', controller.createTestFlow);
route.get('/connections/:id/test-flows/:flowId', controller.testFlowSettings);
route.get('/connections/:id/events/:eventId', controller.event);
route.get('/connections/:id/whatsapp', controller.messagingSettings);
route.put('/connections/:id/whatsapp/rule', controller.messagingRule);
route.get('/connections/:id/whatsapp/jobs', controller.messagingJobs);
route.get('/connections/:id/privacy-requests', controller.privacyRequests);
route.get('/connections/:id/privacy-requests/:requestId/export', controller.privacyExport);
route.post('/connections/:id/privacy-requests/:requestId/complete', controller.completePrivacyRequest);
export default route;
